/** 合并后的黑名单（供 entities.mjs 使用）。 */
export const GENERIC_WORDS = new Set([...GENERIC_WORDS_ZH, ...GENERIC_WORDS_EN]);

/**
 * 中文候选是否命中碎片规则（含模式片段 / 泛词前缀 + 单字尾）。
 * @param {string} key 归一化候选键
 */
export function isFragment(key) {
  const k = String(key ?? '');
  if (!k) return false;
  const isCJKOnly = /^[\u4e00-\u9fff]+$/.test(k);
  if (!isCJKOnly) return GENERIC_PATTERNS.some((p) => k.includes(p));
  for (const p of GENERIC_PATTERNS) if (k.includes(p)) return true;
  // 短片段只按整词段判（防「回滚点」「升级锁」被连坐）
  if (GENERIC_SHORT_SEGMENTS.includes(k)) return true;
  // 泛词前缀 + 长度 2（如「与回滚」「不可」）
  if (k.length === 2 && GENERIC_PREFIXES.includes(k[0])) return true;
  if (k.length >= 3 && GENERIC_PREFIXES.includes(k[0])) {
    const rest = k.slice(1);
    if (GENERIC_WORDS.has(rest) || rest.length <= 2) return true;
  }
  return false;
}

