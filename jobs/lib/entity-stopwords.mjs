/** 词段边界字符（与 lib/reconcile.mjs 的 hasSegment 同口径）。 */
const SEG_BOUNDARY = ' \u0001\u3000-—–_/,、。;；:：()（）[]【】|';

/** 文本里是否含该**完整词段**（两侧为边界或串首尾）。 */
function hasWholeSegment(text, seg) {
  const hay = String(text ?? '').toLowerCase();
  const needle = String(seg ?? '').toLowerCase();
  if (!hay || !needle) return false;
  let from = 0;
  for (;;) {
    const i = hay.indexOf(needle, from);
    if (i < 0) return false;
    const before = i === 0 ? '' : hay[i - 1];
    const after = i + needle.length >= hay.length ? '' : hay[i + needle.length];
    if ((!before || SEG_BOUNDARY.includes(before)) && (!after || SEG_BOUNDARY.includes(after))) return true;
    from = i + 1;
  }
}

